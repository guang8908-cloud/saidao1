# -*- coding: utf-8 -*-
"""执行器：生成分析脚本 → 沙箱执行 → 读写产物。
沙箱 = 独立子进程 + 独立任务目录。真实平台请换成容器/受限解释器。"""
import json
import subprocess
import sys
from pathlib import Path

SCRIPT_TMPL = '''# auto-generated by executor (task={tid}, round={rnd})
{bad_import}
import csv, json

rows = []
with open(r"{csv_path}", encoding="utf-8") as f:
    for r in csv.DictReader(f):
        rows.append(r)


def col(g):
    out = []
    for r in rows:
        v = (r.get("value") or "").strip()
        if r.get("group") == g and v != "":
            try:
                out.append(float(v))
            except ValueError:
                pass
    return out


a = col("A")
b = col("B")


def mean(xs):
    return sum(xs) / len(xs) if xs else float("nan")


res = {{"mean_a": mean(a), "mean_b": mean(b), "diff": mean(b) - mean(a),
       "n_a": len(a), "n_b": len(b), "round": {rnd}}}
with open(r"{out_path}", "w", encoding="utf-8") as f:
    json.dump(res, f, indent=2)
print("ok diff=%.6f n_a=%d n_b=%d" % (res["diff"], res["n_a"], res["n_b"]))
'''


class Executor:
    def __init__(self, store):
        self.store = store

    def generate_script(self, tid, csv_path, out_path, rnd, fault=None):
        bad = ""
        if fault == "import_error":
            bad = "import nonexistent_dep_xyz  # injected fault: 依赖缺失"
        code = SCRIPT_TMPL.format(tid=tid, rnd=rnd, csv_path=csv_path,
                                  out_path=out_path, bad_import=bad)
        rel = f"scripts/analyze_r{rnd}.py"
        self.store.write(tid, rel, code)
        self.store.log(tid, "exec", event="script_generated", round=rnd,
                       script=rel, fault=fault or "none", source="template")
        return self.store.task_dir(tid) / rel

    def write_script(self, tid, code, rnd, source="llm", fault=None):
        if fault == "import_error":
            code = "import nonexistent_dep_xyz  # injected fault: 依赖缺失\n" + code
        rel = f"scripts/analyze_r{rnd}.py"
        self.store.write(tid, rel, code)
        self.store.log(tid, "exec", event="script_generated", round=rnd, script=rel,
                       fault=fault or "none", source=source, chars=len(code))
        return self.store.task_dir(tid) / rel

    @staticmethod
    def unsafe_imports(code):
        """静态检查：模型有时会 import 第三方包，沙箱里必然崩。
        先拦一道，让它变成「可诊断的失败」，而不是神秘超时。"""
        banned = {"pandas", "numpy", "scipy", "matplotlib", "sklearn",
                  "requests", "seaborn", "statsmodels"}
        hits = set()
        for line in code.splitlines():
            s = line.strip()
            if s.startswith("import "):
                for part in s[7:].replace(",", " ").split():
                    m = part.split(".")[0]
                    if m in banned:
                        hits.add(m)
            elif s.startswith("from "):
                parts = s[5:].split()
                if parts:
                    m = parts[0].split(".")[0]
                    if m in banned:
                        hits.add(m)
        return sorted(hits)

    def run_script(self, tid, script_path, rnd, timeout=60):
        try:
            proc = subprocess.run([sys.executable, str(script_path)],
                                  capture_output=True, text=True, timeout=timeout,
                                  cwd=str(self.store.task_dir(tid)))
        except subprocess.TimeoutExpired:
            self.store.log(tid, "exec", event="timeout", round=rnd, timeout=timeout)
            return {"exit": 124, "stdout": "", "stderr": "timeout", "cost_s": timeout}
        tail = (proc.stderr or "").strip().splitlines()[-1:] or [""]
        self.store.log(tid, "exec", event="run", round=rnd, exit=proc.returncode,
                       stdout=(proc.stdout or "").strip()[:300],
                       stderr_last=tail[0][:300])
        return {"exit": proc.returncode, "stdout": proc.stdout or "",
                "stderr": proc.stderr or "", "stderr_last": tail[0]}

    def read_result(self, tid):
        p = self.store.task_dir(tid) / "result.json"
        if not p.exists():
            return None
        try:
            return json.loads(Path(p).read_text(encoding="utf-8"))
        except Exception:
            return None
